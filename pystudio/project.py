    def publish(self):
        from .publish import Publisher
        if self.publisher is not None:
            return
        self._store_fields()
        try:
            self.p.save()
        except OSError as e:
            QMessageBox.critical(self, "Save failed", str(e))
            return
        py = self._python() or self.default_python
        self.pub_log.clear()
        self.b_publish.setEnabled(False)
        self.b_publish.setText("Publishing...")
        self.publisher = Publisher(self.p, py, self.cb_mode.currentData(), self.ck_deb.isChecked(), self)

        def log(t):
            self.pub_log.moveCursor(QTextCursor.End)
            self.pub_log.insertPlainText(t)
            self.pub_log.ensureCursorVisible()
            if self.output is not None:
                self.output.write(t, "info")

        def done(ok, msg):
            self.publisher = None
            self.b_publish.setEnabled(True)
            self.b_publish.setText("Publish")
            if ok:
                QMessageBox.information(self, "Publish", f"Published to:\n{msg}\n\n"
                                        "Run install.sh in that folder to add the app to the menu and desktop.")
        self.publisher.log.connect(log)
        self.publisher.finished.connect(done)
        self.publisher.start()

    def reject(self):
        if self.publisher is not None:
            if QMessageBox.question(self, "Publish", "Publishing is still running. Stop it?") != QMessageBox.Yes:
                return
            self.publisher.cancel()
        super().reject()

    # ------------------------------------------------------------ python/pip
    def _chosen_interpreter(self):
        data = self.cb_interp.currentData()
        if data == "custom":
            return self.custom_python
        return data

    def _python(self):
        interp = self._chosen_interpreter()
        if interp == ".venv":
            p = os.path.join(self.p.root, ".venv", "bin", "python")
            return p if os.path.exists(p) else None
        return interp or self.default_python

    def _log(self, text):
        self.pkg_log.appendPlainText(text.rstrip())
        if self.output is not None:
            self.output.write(text if text.endswith("\n") else text + "\n", "info")

    def _run(self, program, args, done=None, quiet=False):
        if self.proc is not None and self.proc.state() != QProcess.NotRunning:
            QMessageBox.information(self, "Busy", "Wait for the current operation to finish.")
            return
        self.proc = QProcess(self)
        env = QProcessEnvironment.systemEnvironment()
        env.insert("PYTHONUNBUFFERED", "1")
        self.proc.setProcessEnvironment(env)
        self.proc.setProcessChannelMode(QProcess.MergedChannels)
        buf = []

        def read():
            t = bytes(self.proc.readAllStandardOutput()).decode("utf-8", "replace")
            buf.append(t)
            if not quiet:
                self._log(t)

        def fin(code, _s):
            if done:
                done(code, "".join(buf))
        self.proc.readyReadStandardOutput.connect(read)
        self.proc.finished.connect(fin)
        if not quiet:
            self._log(f"> {program} {' '.join(args)}")
        self.proc.start(program, args)

    def _packages_shown(self):
        self.refresh_packages()
        self.pkg_updates.load()

    def refresh_packages(self):
        py = self._python()
        self.pkg_table.setRowCount(0)
        if not py:
            self.pkg_python.setText("The project .venv doesn't exist yet - create it on the Debug page.")
            return
        self.pkg_python.setText(f"Interpreter: {py}")

        def done(code, out):
            try:
                pkgs = json.loads(out[out.index("["):]) if "[" in out else []
            except ValueError:
                pkgs = []
            self.pkg_table.setRowCount(0)
            for pkg in sorted(pkgs, key=lambda x: x["name"].lower()):
                r = self.pkg_table.rowCount()
                self.pkg_table.insertRow(r)
                self.pkg_table.setItem(r, 0, QTableWidgetItem(pkg["name"]))
                self.pkg_table.setItem(r, 1, QTableWidgetItem(pkg["version"]))
            if getattr(self, "pkg_browse", None) is not None:
                self.pkg_browse._search()      # mark what's installed
        self._run(py, ["-m", "pip", "list", "--format", "json", "--disable-pip-version-check"], done, quiet=True)

    def install_package(self):
        name = self.e_pkg.text().strip()
        py = self._python()
        if not name or not py:
            return
        self._run(py, ["-m", "pip", "install", "--disable-pip-version-check", name],
                  lambda code, _o: (self._log("Done." if code == 0 else f"pip exited with code {code}"),
                                    self.refresh_packages()))

    def uninstall_package(self):
        r = self.pkg_table.currentRow()
        py = self._python()
        if r < 0 or not py:
            return
        name = self.pkg_table.item(r, 0).text()
        if QMessageBox.question(self, "Uninstall", f"Uninstall {name}?") != QMessageBox.Yes:
            return
        self._run(py, ["-m", "pip", "uninstall", "-y", name],
                  lambda code, _o: self.refresh_packages())

    def create_venv(self):
        base = "python3"
        venv = os.path.join(self.p.root, ".venv")
        self.b_venv.setEnabled(False)
        self.venv_status.setText("Creating .venv... (installing PySide6 takes a minute)")

        def step2(code, _o):
            if code != 0:
                self._log("Creating the venv failed. On Ubuntu: sudo apt install python3-venv")
                self.b_venv.setEnabled(True)
                self._update_venv_status()
                return
            self._run(os.path.join(venv, "bin", "python"),
                      ["-m", "pip", "install", "--disable-pip-version-check", "PySide6"], step3)

        def step3(code, _o):
            self.b_venv.setEnabled(True)
            self._update_venv_status()
            if code == 0:
                self.cb_interp.setCurrentIndex(1)
                self._log("Project .venv is ready and selected.")
        self._run(base, ["-m", "venv", "--clear", venv], step2)

    # ------------------------------------------------------------ save
    def _store_fields(self):
        p = self.p
        p["name"] = self.e_name.text().strip() or os.path.basename(p.root)
        p["title"] = self.e_title.text().strip()
        p["version"] = self.e_version.text().strip() or "1.0.0"
        p["description"] = self.e_desc.text().strip()
        p["company"] = self.e_company.text().strip()
        p["copyright"] = self.e_copy.text().strip()
        p["icon"] = self.e_icon.text().strip()
        interp = self._chosen_interpreter()
        p["interpreter"] = interp or ""
        p["args"] = self.e_args.text().strip()
        p["workingDir"] = self.e_wd.text().strip()
        p["env"] = self.e_env.toPlainText().strip()
        p["publishSingleFile"] = bool(self.cb_mode.currentData())
        p["publishDeb"] = self.ck_deb.isChecked()
        start = self.cb_startup.currentText().strip().replace("\\", "/")
        if start:
            p["startup"] = start
        refs = [self.ref_list.item(i).data(Qt.UserRole) for i in range(self.ref_list.count())
                if self.ref_list.item(i).checkState() == Qt.Checked]
        p["references"] = [os.path.relpath(r, p.root).replace(os.sep, "/") for r in refs]

    def save(self):
        p = self.p
        for page in (self.settings_page, self.resources_page):
            err = page.validate()
            if err:
                self.nav.setCurrentRow(self.page_names.index("Settings" if page is self.settings_page
                                                             else "Resources"))
                QMessageBox.warning(self, "Project Properties", err)
                return
            page.store()
        start = self.cb_startup.currentText().strip()
        if start and not os.path.isfile(os.path.join(p.root, start)):
            self.nav.setCurrentRow(0)
            QMessageBox.warning(self, "Startup file", f"{start} isn't a file in the project folder.")
            return
        self._store_fields()
        if self.forms and self.cb_form.currentData() and not p.external:
            cls, stem = self.cb_form.currentData()
            if cls != p.current_startup_form():
                err = p.set_startup_form(cls, stem)
                if err:
                    QMessageBox.warning(self, "Startup form", err)
        try:
            p.save()
            from . import mygen
            mygen.write(p)
        except OSError as e:
            QMessageBox.critical(self, "Save failed", str(e))
            return
        self.accept()

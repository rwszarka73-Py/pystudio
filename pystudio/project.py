    def python_files(self):
        out = []
        skip = {"__pycache__", "venv", ".venv", "build", "dist", "publish", ".git"}
        for dirpath, dirs, files in os.walk(self.p.root):
            dirs[:] = sorted(d for d in dirs if d not in skip and not d.startswith(".")
                             and not glob.glob(os.path.join(dirpath, d, "*.pyproj")))
            for f in sorted(files):
                if f.endswith(".py") and not f.startswith("ui_") and f not in ("pystudio_runtime.py", "my.py"):
                    out.append(os.path.relpath(os.path.join(dirpath, f), self.p.root).replace(os.sep, "/"))
            if len(out) > 500:
                break
        return out

    def _refs_page(self):
        """Projects in the solution this one imports from (their folders go on the Python path)."""
        from . import solution as sln
        w = QWidget()
        v = QVBoxLayout(w)
        v.addWidget(QLabel("<b>References</b>"))
        self.ref_list = QListWidget()
        solution = getattr(self.parent(), "solution", None)
        current = set(sln.references(self.p))
        others = [r for r in (solution.projects() if solution else []) if r != self.p.root]
        for root in others:
            other = Project(root)
            it = QListWidgetItem(f"{other.name}    ({solution.rel(root)})")
            it.setData(Qt.UserRole, root)
            it.setFlags(it.flags() | Qt.ItemIsUserCheckable)
            it.setCheckState(Qt.Checked if root in current else Qt.Unchecked)
            if self.p.root in sln.all_references(other):
                it.setToolTip(f"{other.name} already uses {self.p.name} - referencing it back would be circular.")
                it.setFlags(it.flags() & ~Qt.ItemIsEnabled)
            self.ref_list.addItem(it)
        for root in current - set(others):        # referenced but not in this solution (kept as they are)
            it = QListWidgetItem(f"{os.path.basename(root)}    ({root})  - not in this solution")
            it.setData(Qt.UserRole, root)
            it.setFlags((it.flags() | Qt.ItemIsUserCheckable))
            it.setCheckState(Qt.Checked)
            self.ref_list.addItem(it)
        v.addWidget(QLabel(f"Projects <b>{self.p.name}</b> can import from:"))
        v.addWidget(self.ref_list, 1)
        tip = QLabel("A referenced project's folder is added to the Python path when this project runs, is "
                     "debugged or tested, and for IntelliSense: <font face='monospace'>from mathlib import "
                     "Calculator</font>." if others or current else
                     "There are no other projects in the solution yet. Add one with File > Add > New Project "
                     "(for example a Class Library), then check it here.")
        tip.setWordWrap(True)
        tip.setStyleSheet("color: #9a9a9a;")
        v.addWidget(tip)
        return w

    def _update_icon_preview(self):
        path = self.e_icon.text().strip()
        full = path if os.path.isabs(path) else os.path.join(self.p.root, path)
        pm = QPixmap(full) if path and os.path.exists(full) else QPixmap()
        self.icon_preview.setPixmap(pm.scaled(40, 40, Qt.KeepAspectRatio, Qt.SmoothTransformation)
                                    if not pm.isNull() else QPixmap())

    def _pick_icon(self):
        path, _ = QFileDialog.getOpenFileName(self, "Application icon", self.p.root,
                                              "Images (*.png *.svg *.ico *.jpg)")
        if not path:
            return
        rel = os.path.relpath(path, self.p.root)
        if rel.startswith(".."):
            import shutil
            os.makedirs(os.path.join(self.p.root, "images"), exist_ok=True)
            dest = os.path.join(self.p.root, "images", os.path.basename(path))
            shutil.copy2(path, dest)
            rel = os.path.relpath(dest, self.p.root)
        self.e_icon.setText(rel.replace(os.sep, "/"))


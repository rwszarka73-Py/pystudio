DEFAULTS = {
    "name": "", "title": "", "version": "1.0.0", "description": "", "company": "",
    "copyright": "", "icon": "", "startup": "main.py", "startupForm": "",
    "interpreter": "",          # "" = PyStudio's Python, ".venv" = project venv, or a path
    "args": "", "workingDir": "", "env": "",
    "publishSingleFile": False, "publishDeb": True,
}


class Project:
    def __init__(self, root):
        self.root = os.path.abspath(root)
        found = sorted(glob.glob(os.path.join(self.root, "*.pyproj")))
        self.file = found[0] if found else os.path.join(self.root, os.path.basename(self.root) + ".pyproj")
        self.data = dict(DEFAULTS)
        self.data["name"] = os.path.basename(self.root)
        if os.path.exists(self.file):
            try:
                with open(self.file, encoding="utf-8") as f:
                    self.data.update(json.load(f))
            except (OSError, ValueError):
                pass

    # ------------------------------------------------------------ basics
    def __getitem__(self, k):
        return self.data.get(k, DEFAULTS.get(k, ""))

    def __setitem__(self, k, v):
        self.data[k] = v

    @property
    def name(self):
        return self["name"] or os.path.basename(self.root)

    def exists(self):
        return os.path.exists(self.file)

    def save(self):
        with open(self.file, "w", encoding="utf-8", newline="\n") as f:
            json.dump(self.data, f, indent=2)
            f.write("\n")
        self._write_pyproject()

    @property
    def external(self):
        """A project made outside PyStudio (PyQt5, plain scripts...): PyStudio edits and runs it but doesn't
        add its own runtime files or regenerate its forms' code."""
        return bool(self.data.get("external"))

    def _write_pyproject(self):
        """Standard Python metadata (write-only; the .pyproj is PyStudio's source of truth)."""
        if self.external:
            return
        def q(s):
            return json.dumps(str(s))
        pkg = re.sub(r"[^A-Za-z0-9_.-]", "-", self.name).lower() or "app"
        lines = ["[project]", f"name = {q(pkg)}", f"version = {q(self['version'] or '1.0.0')}"]
        if self["description"]:
            lines.append(f"description = {q(self['description'])}")
        if self["company"]:
            lines.append(f"authors = [{{ name = {q(self['company'])} }}]")
        lines += ['requires-python = ">=3.10"', 'dependencies = ["PySide6"]', ""]
        lines += ["# Generated by PyStudio from " + os.path.basename(self.file), ""]
        path = os.path.join(self.root, "pyproject.toml")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                if "Generated by PyStudio" not in f.read():
                    return   # the user's own pyproject.toml - leave it alone
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))

    # ------------------------------------------------------------ files
    def forms(self):
        """[(class_name, stem)] for every .ui form in the project root."""
        out = []
        for ui in sorted(glob.glob(os.path.join(self.root, "*.ui"))):
            stem = os.path.splitext(os.path.basename(ui))[0]
            try:
                with open(ui, encoding="utf-8") as f:
                    m = re.search(r"<class>(\w+)</class>", f.read())
                out.append((m.group(1) if m else stem.capitalize(), stem))
            except OSError:
                pass
        return out

    def ensure_runtime(self):
        """Write/refresh pystudio_runtime.py in the project."""
        if self.external:
            return
        path = os.path.join(self.root, "pystudio_runtime.py")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                m = re.search(r"RUNTIME_VERSION = (\d+)", f.read())
            if m and int(m.group(1)) >= RUNTIME_VERSION:
                return
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(RUNTIME_SOURCE)

    # ------------------------------------------------------------ running
    def python(self, default_python):
        interp = self["interpreter"]
        if interp == ".venv":
            p = os.path.join(self.root, ".venv", "bin", "python")
            return p if os.path.exists(p) else default_python
        return interp or default_python

    def run_args(self):
        try:
            return shlex.split(self["args"] or "")
        except ValueError:
            return (self["args"] or "").split()

    def working_dir(self):
        wd = self["workingDir"]
        if not wd:
            return self.root
        return wd if os.path.isabs(wd) else os.path.join(self.root, wd)

    def env(self):
        out = {}
        for line in (self["env"] or "").splitlines():
            if "=" in line and not line.strip().startswith("#"):
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip()
        return out

    # ------------------------------------------------------------ startup form
    def set_startup_form(self, cls, stem):
        """Rewrite main.py so it opens the chosen form. Returns error text or ''."""
        main = os.path.join(self.root, self["startup"] or "main.py")
        if not os.path.exists(main):
            return f"{os.path.basename(main)} not found."
        with open(main, encoding="utf-8") as f:
            src = f.read()
        m_imp = re.search(r"^from (\w+) import (\w+)\s*$", src, re.M)
        m_new = re.search(r"^(\s*)(\w+)\s*=\s*(\w+)\(\)\s*$", src, re.M)
        if not m_imp or not m_new or m_new.group(3) != m_imp.group(2):
            return ("main.py doesn't look like PyStudio's startup code, so it wasn't changed. "
                    f"Change it by hand to create {cls} from {stem}.py.")
        src = src[:m_imp.start()] + f"from {stem} import {cls}" + src[m_imp.end():]
        m_new = re.search(r"^(\s*)(\w+)\s*=\s*(\w+)\(\)\s*$", src, re.M)
        src = src[:m_new.start()] + f"{m_new.group(1)}{m_new.group(2)} = {cls}()" + src[m_new.end():]
        with open(main, "w", encoding="utf-8", newline="\n") as f:
            f.write(src)
        self["startupForm"] = cls
        return ""

    def current_startup_form(self):
        main = os.path.join(self.root, self["startup"] or "main.py")
        try:
            with open(main, encoding="utf-8") as f:
                m = re.search(r"^from (\w+) import (\w+)\s*$", f.read(), re.M)
            return m.group(2) if m else ""
        except OSError:
            return ""



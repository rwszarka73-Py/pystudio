"""Projects made outside PyStudio (PyQt5 apps, scripts, Qt Designer forms loaded with uic.loadUi...):
PyStudio opens, edits, runs and debugs them without adding its own files or rewriting their forms."""
import os
import re
import xml.etree.ElementTree as ET

SKIP = ("__pycache__", "venv", ".venv", "build", "dist", "publish", "node_modules")


def _py_files(root, limit=500):
    n = 0
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d not in SKIP]
        for f in files:
            if f.endswith(".py"):
                n += 1
                if n > limit:
                    return
                yield os.path.join(dirpath, f)


def _read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def uses_pystudio(root):
    """True if the project's own code uses PyStudio's runtime (a PyStudio project)."""
    for p in _py_files(root):
        name = os.path.basename(p)
        if name in ("pystudio_runtime.py", "my.py") or name.startswith("ui_"):
            continue
        if "pystudio_runtime" in _read(p):
            return True
    return False


def uses_pyqt(root):
    return any(re.search(r"^\s*(from|import)\s+PyQt[56]\b", _read(p), re.M) for p in _py_files(root))


def loads_ui_at_runtime(root):
    """The code loads .ui files itself (uic.loadUi / QUiLoader) - so the .ui must keep Qt's layouts."""
    return any(re.search(r"\bloadUi(Type)?\s*\(|QUiLoader\s*\(", _read(p)) for p in _py_files(root))


def _imported_names(root):
    names = set()
    for p in _py_files(root):
        for m in re.finditer(r"^\s*(?:from\s+([\w.]+)\s+import|import\s+([\w.]+))", _read(p), re.M):
            names.add((m.group(1) or m.group(2)).split(".")[0])
    return names


def cleanup_generated(root):
    """Remove files an earlier PyStudio added to a project it didn't make - only files PyStudio generated
    (they carry its marker) that the project's code doesn't use. Returns notes for the Output window."""
    notes = []
    used = _imported_names(root)
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d not in SKIP]
        for f in files:
            path = os.path.join(dirpath, f)
            text = None
            if f == "pystudio_runtime.py" and "pystudio_runtime" not in used:
                text = _read(path)
                ours = "generated by PyStudio" in text
            elif f == "my.py" and "my" not in used:
                text = _read(path)
                ours = "PyStudio" in text[:400]
            elif f == "pyproject.toml":
                text = _read(path)
                ours = "Generated by PyStudio" in text
            elif f.startswith("ui_") and f.endswith(".py") and f[:-3] not in used:
                text = _read(path)
                # pyside6-uic output, next to a .ui with the same stem (not the project's own pyuic5 output)
                ours = "Qt User Interface Compiler" in text[:600] and "PyQt" not in text[:600] and \
                    os.path.exists(os.path.join(dirpath, f[3:-3] + ".ui"))
            else:
                continue
            if ours:
                try:
                    os.remove(path)
                    notes.append(f"removed {os.path.relpath(path, root)} (PyStudio had added it; your code doesn't use it)")
                except OSError:
                    pass
    return notes


def _has_layouts(path):
    try:
        top = ET.parse(path).getroot().find("widget")
    except (ET.ParseError, OSError):
        return False
    return top is not None and top.find(".//layout") is not None


def converted_forms(root):
    """Forms an earlier PyStudio converted (form.ui without layouts, form.ui.bak with them)."""
    notes = []
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d not in SKIP]
        for f in files:
            if f.endswith(".ui.bak"):
                ui = os.path.join(dirpath, f[:-4])
                bak = os.path.join(dirpath, f)
                if os.path.exists(ui) and _has_layouts(bak) and not _has_layouts(ui):
                    notes.append(f"{os.path.relpath(ui, root)} was converted and lost its layouts. To put the "
                                 f"original back: right-click {f} in Solution Explorer > Restore Backup")
    return notes


def has_code(root, depth=2):
    """Python files or forms within a couple of folder levels (code in app/ or src/ counts)."""
    base = os.path.abspath(root).count(os.sep)
    for dirpath, dirs, files in os.walk(root):
        if dirpath.count(os.sep) - base >= depth:
            dirs[:] = []
        dirs[:] = [d for d in dirs if not d.startswith(".") and d not in SKIP]
        if any(f.endswith((".py", ".ui")) for f in files):
            return True
    return False


def find_startup(root):
    """The script that starts the program: main.py (top level first), else app.py/__main__.py, else a file
    with  if __name__ == "__main__".  Path relative to root, or ''."""
    best = None
    for p in _py_files(root):
        rel = os.path.relpath(p, root)
        name = os.path.basename(p)
        if name.startswith(("ui_", "test_")) or name in ("pystudio_runtime.py", "my.py", "setup.py"):
            continue
        depth = rel.count(os.sep)
        rank = {"main.py": 0, "__main__.py": 1, "app.py": 2}.get(name)
        if rank is None:
            rank = 3 if re.search(r"__name__\s*==\s*['\"]__main__['\"]", _read(p)) else None
        if rank is None:
            continue
        key = (depth, rank, rel)
        if best is None or key < best:
            best = key
    if best:
        return best[2].replace(os.sep, "/")
    scripts = [os.path.relpath(p, root) for p in _py_files(root)
               if not os.path.basename(p).startswith(("ui_", "test_"))
               and os.path.basename(p) not in ("pystudio_runtime.py", "my.py", "setup.py", "__init__.py")]
    return scripts[0].replace(os.sep, "/") if len(scripts) == 1 else ""


def restore_backup(bak):
    """form.ui.bak -> form.ui (the converted file is kept as form.ui.converted)."""
    ui = bak[:-4]
    if os.path.exists(ui):
        keep = ui + ".converted"
        if os.path.exists(keep):
            os.remove(keep)
        os.replace(ui, keep)
    os.replace(bak, ui)
    return ui

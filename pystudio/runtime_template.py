_BUTTONS = {
    "OK": QMessageBox.Ok, "OKCancel": QMessageBox.Ok | QMessageBox.Cancel,
    "YesNo": QMessageBox.Yes | QMessageBox.No,
    "YesNoCancel": QMessageBox.Yes | QMessageBox.No | QMessageBox.Cancel,
    "RetryCancel": QMessageBox.Retry | QMessageBox.Cancel,
    "AbortRetryIgnore": QMessageBox.Abort | QMessageBox.Retry | QMessageBox.Ignore,
}
_ICONS = {"None": QMessageBox.NoIcon, "Information": QMessageBox.Information,
          "Warning": QMessageBox.Warning, "Error": QMessageBox.Critical,
          "Question": QMessageBox.Question}
_RESULTS = {QMessageBox.Ok: "OK", QMessageBox.Cancel: "Cancel", QMessageBox.Yes: "Yes",
            QMessageBox.No: "No", QMessageBox.Retry: "Retry", QMessageBox.Abort: "Abort",
            QMessageBox.Ignore: "Ignore"}


def msgbox(text, title="", buttons="OK", icon="Information", parent=None):
    """Like VB's MsgBox:  if msgbox("Save changes?", "MyApp", "YesNo", "Question") == "Yes": ..."""
    box = QMessageBox(_ICONS.get(icon, QMessageBox.Information),
                      title or QApplication.applicationDisplayName() or "Message", str(text),
                      _BUTTONS.get(buttons, QMessageBox.Ok), parent or QApplication.activeWindow())
    return _RESULTS.get(QMessageBox.StandardButton(box.exec()), "OK")

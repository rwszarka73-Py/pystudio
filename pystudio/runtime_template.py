_HERE = getattr(sys, "_MEIPASS", None) or os.path.dirname(os.path.abspath(__file__))


def _project():
    for path in glob.glob(os.path.join(_HERE, "*.pyproj")):
        try:
            with open(path, encoding="utf-8") as f:
                return json.load(f)
        except (OSError, ValueError):
            pass
    return {}


def _package_name(name):
    import re
    pkg = re.sub(r"[^a-z0-9+.-]+", "-", (name or "app").lower()).strip("-.+")
    return pkg if len(pkg) >= 2 else (pkg + "-app").lstrip("-")


def setup_app(app):
    if getattr(sys, "frozen", False):
        os.chdir(_HERE)   # relative image paths (PictureBox, icons) resolve like in F5 runs
    p = _project()
    if p.get("name"):
        app.setDesktopFileName(_package_name(p["name"]))   # dock icon on Wayland
    if p.get("name"):
        app.setApplicationName(p["name"])
        app.setApplicationDisplayName(p.get("title") or p["name"])
    if p.get("version"):
        app.setApplicationVersion(p["version"])
    icon = p.get("icon")
    if icon:
        icon = icon if os.path.isabs(icon) else os.path.join(_HERE, icon)
        if os.path.exists(icon):
            app.setWindowIcon(QIcon(icon))
    if p.get("saveSettingsOnExit", True):
        app.aboutToQuit.connect(_save_settings_on_exit)


def _size(widget):
    v = widget.property("designSize")
    if v:
        try:
            w, h = (int(x) for x in str(v).split(","))
            return w, h
        except ValueError:
            pass
    return widget.width(), widget.height()


class _Anchors(QObject):
    """Keeps anchored controls' distances to their container edges (like WinForms Anchor)."""

    def __init__(self, container):
        super().__init__(container)
        self.c = container
        self.dw, self.dh = _size(container)
        self.items = []
        for ch in container.findChildren(QWidget, options=Qt.FindDirectChildrenOnly):
            a = ch.property("anchor")
            if not a or ch.property("dock"):
                continue
            sides = {s.strip().lower() for s in str(a).split(",")}
            g = ch.geometry()
            self.items.append((ch, sides, g.x(), g.y(), g.width(), g.height()))
        container.installEventFilter(self)
        self.apply()

    def eventFilter(self, obj, ev):
        if ev.type() == QEvent.Resize:
            self.apply()
        return False

    def apply(self):
        W, H = self.c.width(), self.c.height()
        for ch, sides, x, y, w, h in self.items:
            rm, bm = self.dw - (x + w), self.dh - (y + h)
            if "left" in sides and "right" in sides:
                nx, nw = x, max(1, W - x - rm)
            elif "right" in sides:
                nx, nw = W - rm - w, w
            elif "left" in sides:
                nx, nw = x, w
            else:
                nx, nw = round((x + w / 2) * W / max(1, self.dw) - w / 2), w
            if "top" in sides and "bottom" in sides:
                ny, nh = y, max(1, H - y - bm)
            elif "bottom" in sides:
                ny, nh = H - bm - h, h
            elif "top" in sides:
                ny, nh = y, h
            else:
                ny, nh = round((y + h / 2) * H / max(1, self.dh) - h / 2), h
            ch.setGeometry(nx, ny, nw, nh)


def _padding(container):
    """WinForms Padding ("left,top,right,bottom"): docked children keep that far from the edges."""
    try:
        v = [int(x) for x in str(container.property("padding") or "").split(",")]
        return v if len(v) == 4 else [0, 0, 0, 0]
    except ValueError:
        return [0, 0, 0, 0]


def _interior(container):
    l, t, r, b = _padding(container)
    return _interior_raw(container).adjusted(l, t, -r, -b)


def _interior_raw(container):
    from PySide6.QtCore import QRect
    from PySide6.QtWidgets import QFrame, QGroupBox
    if isinstance(container, QGroupBox):
        r = container.contentsRect()
        top = container.fontMetrics().height() + 2
        return QRect(r.x() + 2, r.y() + top, max(0, r.width() - 4), max(0, r.height() - top - 2))
    if isinstance(container, QFrame) and type(container) is QFrame:
        return container.contentsRect()
    return container.rect()


class _Docks(QObject):
    """WinForms Dock: Top/Bottom/Left/Right strips in z-order, Fill takes the rest."""

    def __init__(self, container):
        super().__init__(container)
        self.c = container
        self.kids = [ch for ch in container.findChildren(QWidget, options=Qt.FindDirectChildrenOnly)
                     if ch.property("dock")]
        container.installEventFilter(self)
        self.apply()

    def eventFilter(self, obj, ev):
        if ev.type() in (QEvent.Resize, QEvent.Show):
            self.apply()
        return False

    def apply(self):
        rem = _interior(self.c)
        fills = []
        for ch in self.kids:
            d = ch.property("dock")
            h, w = ch.height(), ch.width()
            if d == "Fill":
                fills.append(ch)
            elif d == "Top":
                ch.setGeometry(rem.x(), rem.y(), rem.width(), h)
                rem.setTop(rem.top() + h)
            elif d == "Bottom":
                ch.setGeometry(rem.x(), rem.bottom() - h + 1, rem.width(), h)
                rem.setBottom(rem.bottom() - h)
            elif d == "Left":
                ch.setGeometry(rem.x(), rem.y(), w, rem.height())
                rem.setLeft(rem.left() + w)
            elif d == "Right":
                ch.setGeometry(rem.right() - w + 1, rem.y(), w, rem.height())
                rem.setRight(rem.right() - w)
        for ch in fills:
            ch.setGeometry(rem)


class _FormShow(QObject):
    def __init__(self, window):
        super().__init__(window)
        self.done = False
        window.installEventFilter(self)

    def eventFilter(self, win, ev):
        if ev.type() == QEvent.Show and not self.done:
            self.done = True
            if win.property("startPosition") == "CenterScreen":
                screen = win.screen() or QGuiApplication.primaryScreen()
                if screen:
                    r = win.frameGeometry()
                    r.moveCenter(screen.availableGeometry().center())
                    win.move(r.topLeft())
            if win.property("borderStyle") in ("FixedSingle", "Fixed3D", "FixedDialog"):
                win.setFixedSize(win.size())
        return False


def setup_form(window):
    containers = []
    own = _own_widgets(window)        # a UserControl on the form sets up its own controls
    for c in [window.centralWidget()] + own:
        if c is not None and c not in containers:
            containers.append(c)
    for container in containers:
        kids = container.findChildren(QWidget, options=Qt.FindDirectChildrenOnly)
        if any(ch.property("anchor") for ch in kids):
            _Anchors(container)
        if any(ch.property("dock") for ch in kids):
            _Docks(container)
    from PySide6.QtWidgets import QSplitter
    for sp in [w for w in own if isinstance(w, QSplitter)]:
        dist = sp.property("splitterDistance")
        if dist:
            total = (sp.width() if sp.orientation() == Qt.Horizontal else sp.height()) - sp.handleWidth()
            sp.setSizes([int(dist), max(10, total - int(dist))])

    _components(window)
    for de in [w for w in own if isinstance(w, QDateTimeEdit)]:
        if de.property("valueToday"):
            de.setDateTime(QDateTime.currentDateTime().addSecs(-QTime.currentTime().second()))
    _bind_data(window)     # after valueToday, so bound dates show the row's value
    _form_extras(window)   # AcceptButton, CancelButton, DialogResult, show_dialog()
    _hr_register(window)   # Hot Reload while PyStudio runs the program (designer changes appear live)
    if isinstance(window, UserControl):
        return             # a control on a form: no window settings

    flags = window.windowFlags()
    if window.property("borderStyle") == "None":
        flags |= Qt.FramelessWindowHint
    maxbox = window.property("maximizeBox")
    minbox = window.property("minimizeBox")
    if maxbox is False or minbox is False:
        flags |= Qt.CustomizeWindowHint | Qt.WindowTitleHint | Qt.WindowCloseButtonHint
        flags = (flags | Qt.WindowMaximizeButtonHint) if maxbox is not False else (flags & ~Qt.WindowMaximizeButtonHint)
        flags = (flags | Qt.WindowMinimizeButtonHint) if minbox is not False else (flags & ~Qt.WindowMinimizeButtonHint)
    if window.property("topMost"):
        flags |= Qt.WindowStaysOnTopHint
    window.setWindowFlags(flags)

    state = window.property("windowState")
    if state == "Maximized":
        window.setWindowState(Qt.WindowMaximized)
    elif state == "Minimized":
        window.setWindowState(Qt.WindowMinimized)
    _FormShow(window)

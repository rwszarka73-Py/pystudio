class OpenFileDialog:
    def __init__(self, parent, title="", filter="All files (*)", initialDirectory="",
                 multiselect=False, fileName=""):
        self.parent, self.title, self.filter = parent, title or "Open", filter
        self.initial_directory, self.multiselect = initialDirectory, multiselect
        self.file_name, self.file_names = fileName, []

    def show_dialog(self):
        start = self.file_name or self.initial_directory
        if self.multiselect:
            files, _ = QFileDialog.getOpenFileNames(self.parent, self.title, start, self.filter)
            if files:
                self.file_names, self.file_name = files, files[0]
            return bool(files)
        f, _ = QFileDialog.getOpenFileName(self.parent, self.title, start, self.filter)
        if f:
            self.file_name, self.file_names = f, [f]
        return bool(f)


class SaveFileDialog:
    def __init__(self, parent, title="", filter="All files (*)", initialDirectory="", fileName=""):
        self.parent, self.title, self.filter = parent, title or "Save As", filter
        self.initial_directory, self.file_name = initialDirectory, fileName

    def show_dialog(self):
        start = self.file_name
        if self.initial_directory and not os.path.isabs(start or ""):
            start = os.path.join(self.initial_directory, start or "")
        f, _ = QFileDialog.getSaveFileName(self.parent, self.title, start, self.filter)
        if f:
            self.file_name = f
        return bool(f)


class FolderBrowserDialog:
    def __init__(self, parent, description="", selectedPath=""):
        self.parent, self.description, self.selected_path = parent, description, selectedPath

    def show_dialog(self):
        d = QFileDialog.getExistingDirectory(self.parent, self.description or "Select Folder",
                                             self.selected_path)
        if d:
            self.selected_path = d
        return bool(d)


class ColorDialog:
    def __init__(self, parent, color="#000000"):
        self.parent, self.color = parent, color

    @property
    def qcolor(self):
        return QColor(self.color)

    def show_dialog(self):
        c = QColorDialog.getColor(QColor(self.color), self.parent)
        if c.isValid():
            self.color = c.name()
        return c.isValid()


class FontDialog:
    def __init__(self, parent):
        self.parent, self.font = parent, QFont(parent.font())

    def show_dialog(self):
        a, b = QFontDialog.getFont(self.font, self.parent)
        ok, font = (a, b) if isinstance(a, bool) else (b, a)
        if ok:
            self.font = font
        return ok


class ImageList:
    """Pictures for TreeView/ListView/toolbar items:  self.ui.imageList1.icon(0)"""

    def __init__(self, parent, images=(), imageSize=16):
        from PySide6.QtCore import QSize
        self.parent = parent
        self.paths = [p if os.path.isabs(p) else os.path.join(_HERE, p) for p in images]
        self.image_size = QSize(int(imageSize), int(imageSize))
        self.images = [QIcon(p) for p in self.paths]

    def icon(self, index):
        return self.images[index]

    def pixmap(self, index):
        return self.images[index].pixmap(self.image_size)

    def __len__(self):
        return len(self.images)


_FACTORIES = {"OpenFileDialog": OpenFileDialog, "SaveFileDialog": SaveFileDialog, "ImageList": ImageList,
              "FolderBrowserDialog": FolderBrowserDialog, "ColorDialog": ColorDialog,
              "FontDialog": FontDialog}


def _components(window):
    raw = window.property("components")
    if not raw:
        return
    try:
        comps = json.loads(raw)
    except ValueError:
        return
    target = getattr(window, "ui", window)   # self.ui.timer1, like controls
    made = []
    for c in comps:
        t, name, p = c.get("type"), c.get("name"), dict(c.get("props") or {})
        if t == "Timer":
            obj = QTimer(window)
            obj.setInterval(int(p.get("interval", 100)))
            if p.get("enabled"):
                obj.start()
        elif t in _FACTORIES:
            obj = _FACTORIES[t](window, **p)
        else:
            continue
        setattr(target, name, obj)
        if isinstance(obj, QObject):
            obj.setObjectName(name)
        made.append(obj)
    _link_components(target, made)
    _components_extra(window, target, made)   # menus, tray icon menu, right-click menus



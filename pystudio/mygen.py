"""Generates my.py - the project's settings, resources, connections and queries
(like VB's My.Settings / My.Resources and a typed TableAdapter per query)."""
import glob
import keyword
import os
import re

from . import dbcore

SETTING_TYPES = ["String", "Integer", "Decimal", "Boolean", "Color", "Date", "StringList"]
PY_TYPES = {"String": "str", "Integer": "int", "Decimal": "float", "Boolean": "bool",
            "Color": "str", "Date": "datetime.date", "StringList": "list[str]"}
RESOURCE_TYPES = ["String", "Image", "Text", "File"]
RES_PY = {"String": "str", "Image": "QPixmap", "Text": "str", "File": "str"}
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".bmp", ".svg", ".ico", ".webp"}
TEXT_EXT = {".txt", ".md", ".csv", ".json", ".html", ".xml", ".sql", ".css", ".ini", ".log"}


def valid_name(name):
    return bool(re.fullmatch(r"[A-Za-z_]\w*", name or "")) and not keyword.iskeyword(name)


def ident(text):
    s = re.sub(r"\W", "_", text or "").strip("_") or "item"
    if s[0].isdigit():
        s = "_" + s
    return s + "_" if keyword.iskeyword(s) else s


def resource_type_for(path):
    ext = os.path.splitext(path)[1].lower()
    return "Image" if ext in IMAGE_EXT else ("Text" if ext in TEXT_EXT else "File")


def query_files(root):
    """{name: path} for queries/*.sql (and *.sql in the project root)."""
    out = {}
    for path in sorted(glob.glob(os.path.join(root, "*.sql")) +
                       glob.glob(os.path.join(root, "queries", "*.sql"))):
        name = os.path.splitext(os.path.basename(path))[0]
        if valid_name(name):
            out[name] = path
    return out


def _doc(text):
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _lit(v):
    return repr(v)


def generate(project):
    """Source text of my.py for a Project."""
    data = project.data
    settings = [s for s in data.get("settings", []) if valid_name(s.get("name"))]
    resources = [r for r in data.get("resources", []) if valid_name(r.get("name"))]
    conns = [c for c in data.get("connections", []) if c.get("name")]
    queries = {}
    for name, path in query_files(project.root).items():
        try:
            with open(path, encoding="utf-8") as f:
                queries[name] = dbcore.parse_query_file(f.read())
        except OSError:
            pass

    L = ['"""My - settings, resources, data connections and queries for '
         f'{project.name}.',
         "",
         f"Generated by PyStudio from {os.path.basename(project.file)} - don't edit (it gets replaced).",
         "Change them in Project Properties (Settings, Resources), Server Explorer and queries/*.sql.",
         "",
         "    import my",
         "    my.settings.UserName = \"Rob\"           # saved automatically when the app closes",
         "    self.ui.pictureBox1.setPixmap(my.resources.Logo)",
         "    for row in my.queries.GetCustomers(state=\"NE\"):",
         "        print(row.Name, row.City)",
         "    my.fill(self.ui.dataGridView1, my.queries.GetCustomers())",
         "    my.save(self.ui.dataGridView1)          # write grid edits back (VB: TableAdapter.Update)",
         '"""',
         "import datetime",
         "",
         "from PySide6.QtGui import QPixmap",
         "",
         "import pystudio_runtime as _rt",
         "from pystudio_runtime import (DataError, DataTable, Row, current_row, execute, fill, query,  # noqa: F401",
         "                              scalar, selected_value, save, refresh, has_changes, can_save,",
         "                              add_row, delete_row)",
         "", ""]

    # ---- settings
    L.append("class _Settings(_rt.SettingsBase):")
    L.append('    """My.Settings - User settings can be changed and are saved per user; '
             'Application settings are read-only."""')
    if not settings:
        L.append("    pass")
    for s in settings:
        n, t = s["name"], s.get("type", "String")
        py = PY_TYPES.get(t, "str")
        scope = s.get("scope", "User")
        L += ["",
              "    @property",
              f"    def {n}(self) -> {py}:",
              f'        """{scope} setting ({t}). Default: {_doc(str(s.get("value", "")))}"""',
              f"        return self._get({n!r})"]
        if scope != "Application":
            L += ["",
                  f"    @{n}.setter",
                  f"    def {n}(self, value: {py}):",
                  f"        self._set({n!r}, value)"]
    L += ["", ""]

    # ---- resources
    L.append("class _Resources(_rt.ResourcesBase):")
    L.append('    """My.Resources - strings, images and files added in Project Properties > Resources."""')
    if not resources:
        L.append("    pass")
    for r in resources:
        n, t = r["name"], r.get("type", "String")
        desc = r.get("value", "") if t == "String" else f"file {r.get('value', '')}"
        L += ["",
              "    @property",
              f"    def {n}(self) -> {RES_PY.get(t, 'str')}:",
              f'        """{t} resource: {_doc(str(desc)[:80])}"""',
              f"        return self._get({n!r})"]
    L += ["", ""]

    # ---- connections
    L.append("class _Connections:")
    L.append('    """Open DB-API connections (Server Explorer). Each opens on first use and is reused."""')
    if not conns:
        L.append("    pass")
    for c in conns:
        n = ident(c["name"])
        L += ["",
              "    @property",
              f"    def {n}(self):",
              f'        """{_doc(dbcore.connection_summary(c))}"""',
              f"        return _rt.db({c['name']!r})"]
    L += ["", ""]

    # ---- queries
    L.append("class _Queries:")
    L.append('    """Saved queries (queries/*.sql). Each returns a DataTable of rows."""')
    if not queries:
        L.append("    pass")
    for name, q in queries.items():
        args = []
        for p, default in q["params"].items():
            pn = ident(p)
            args.append(f"{pn}={_lit(dbcore.coerce_param(default))}" if default is not None else pn)
        # parameters without defaults must come first
        args.sort(key=lambda a: "=" in a)
        sig = ", ".join(["self"] + args)
        call = ", ".join([repr(name)] + [f"{p}={ident(p)}" for p in q["params"]])
        sql_preview = " ".join(q["sql"].split())[:300]
        doc = (q["description"] + "\n\n        " if q["description"] else "") + sql_preview
        if q["connection"]:
            doc += f"\n\n        Connection: {q['connection']}"
        L += ["",
              f"    def {name}({sig}) -> DataTable:",
              f'        """{_doc(doc)}"""',
              f"        return _rt.query({call})"]
    L += ["", ""]

    L += ["settings = _Settings()",
          "resources = _Resources()",
          "connections = _Connections()",
          "queries = _Queries()",
          ""]
    return "\n".join(L)


def needed(project):
    d = project.data
    return bool(d.get("settings") or d.get("resources") or d.get("connections")
                or query_files(project.root)) or os.path.exists(os.path.join(project.root, "my.py"))


def write(project):
    """Write my.py if the project uses settings/resources/data. Returns True if it changed."""
    if getattr(project, "external", False) or not needed(project):
        return False
    path = os.path.join(project.root, "my.py")
    text = generate(project)
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True
